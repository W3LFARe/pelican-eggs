        var("Allow Flight", "Whether players are allowed to fly in Survival mode (true or false).",
            "ALLOW_FLIGHT", "true", "required|string|in:true,false"),
        var("Max Players", "Maximum number of players allowed on the server at once.",
            "MAX_PLAYERS", "5", "required|numeric|min:1"),
