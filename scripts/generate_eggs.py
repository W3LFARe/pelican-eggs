# --------------------------------------------------------------------------
# pelican-start.sh (written by the installer; runs on every server start)
# Placeholders: @@REPO@@ @@SHORT@@
# --------------------------------------------------------------------------
START_SCRIPT = r'''#!/bin/bash
# Generated by W3LFARe/pelican-eggs. Recreated on every (re)install - do not edit.
cd "$(dirname "$(readlink -f "$0")")" || exit 1
REPO="@@REPO@@"
# .bin only fills gaps (static jq, busybox unzip); tools in the image win.
export PATH="$PATH:$PWD/.bin"

log() { echo "[W3LFARe-Egg] $*"; }

# fetch URL DEST - never leaves a partial/empty/error-page file behind.
fetch() {
    if curl -fsSL --retry 3 --retry-delay 2 "$1" -o "$2.tmp" && [ -s "$2.tmp" ]; then
        mv "$2.tmp" "$2"
        return 0
    fi
    rm -f "$2.tmp"
    return 1
}

# Which upstream version to run: UPSTREAM_REF if set (e.g. "main"), otherwise the
# newest published GitHub Release tag. Release tags are only created after the
# upstream smoke test passed, so a broken commit on main never reaches servers.
resolve_ref() {
    if [ -n "${UPSTREAM_REF:-}" ]; then
        echo "${UPSTREAM_REF}"
        return 0
    fi
    curl -fsSL --retry 2 "https://api.github.com/repos/${REPO}/releases/latest" 2>/dev/null \
        | sed -n 's/.*"tag_name"[[:space:]]*:[[:space:]]*"\([^"]*\)".*/\1/p' | head -n 1
}

# update_upstream REF - download pack.env + launch.sh together, or change nothing.
update_upstream() {
    local base="https://raw.githubusercontent.com/${REPO}/$1"
    if ! fetch "${base}/pack.env" pack.env.new || ! fetch "${base}/launch.sh" launch.sh.new; then
        rm -f pack.env.new launch.sh.new
        return 1
    fi
    mv pack.env.new pack.env
    mv launch.sh.new launch.sh
    sed -i 's/\r$//' pack.env launch.sh
    sed -i 's|/data|/home/container|g; s|/pack.env|/home/container/pack.env|g' launch.sh
    # Older upstream releases hard-code port 25565; newer ones honour SERVER_PORT.
    if [ -n "${SERVER_PORT:-}" ] && ! grep -q 'SERVER_PORT' launch.sh; then
        sed -i "s/25565/${SERVER_PORT}/g" launch.sh
    fi
    chmod +x launch.sh
    echo "$1" > .upstream-ref
}

# Installer mode: must succeed, otherwise the install fails loudly.
if [ "${1:-}" = "--fetch-only" ]; then
    ref="$(resolve_ref)"
    if [ -z "$ref" ]; then
        log "Warning: could not resolve the latest release of ${REPO}; using 'main'."
        ref="main"
    fi
    log "Fetching pack.env and launch.sh from ${REPO}@${ref}..."
    if ! update_upstream "$ref"; then
        log "ERROR: could not download pack.env/launch.sh from ${REPO}@${ref}"
        exit 1
    fi
    exit 0
fi

# Minecraft EULA: only ever accepted by the server owner (Pelican's EULA prompt
# writes eula=true into eula.txt). Never accepted on anyone's behalf.
if ! grep -qi '^eula=true' eula.txt 2>/dev/null; then
    [ -f eula.txt ] || echo "eula=false" > eula.txt
    echo "You need to agree to the EULA in order to run the server. Go to eula.txt for more info."
    exit 0
fi
export EULA="true"

mkdir -p custom_mods custom_config

case "${AUTO_UPDATE:-1}" in
    1|[Tt][Rr][Uu][Ee])
        log "AUTO_UPDATE is enabled! Checking ${REPO} for the latest @@SHORT@@ release..."
        ref="$(resolve_ref)"
        if [ -z "$ref" ]; then
            log "Warning: could not resolve the latest release; keeping the installed launch.sh."
        elif update_upstream "$ref"; then
            log "Using ${REPO}@${ref}"
        else
            log "Warning: could not download from GitHub; keeping the installed launch.sh."
        fi
        ;;
    *)
        log "AUTO_UPDATE is disabled. Booting the installed @@SHORT@@ version ($(cat .upstream-ref 2>/dev/null || echo unknown))..."
        ;;
esac

if [ ! -s launch.sh ] || [ ! -s pack.env ]; then
    log "ERROR: launch.sh/pack.env missing. Reinstall the server from the panel (Settings -> Reinstall)."
    exit 1
fi

# JVM heap: when JVM_OPTS is empty, size it from the memory allocated in the panel
# (leave >=1 GB or 15% for metaspace, threads and off-heap) so the container is
# never OOM-killed by a heap larger than its limit.
if [ -z "${JVM_OPTS:-}" ] && [ "${SERVER_MEMORY:-0}" -gt 0 ] 2>/dev/null; then
    reserve=$(( SERVER_MEMORY * 15 / 100 ))
    [ "$reserve" -lt 1024 ] && reserve=1024
    xmx=$(( SERVER_MEMORY - reserve ))
    [ "$xmx" -lt 1024 ] && xmx=1024
    xms=$(( xmx / 2 ))
    export JVM_OPTS="-Xms${xms}M -Xmx${xmx}M"
    log "JVM_OPTS not set; sized from the ${SERVER_MEMORY} MB allocation: ${JVM_OPTS}"
fi

for tool in jq unzip; do
    command -v "$tool" > /dev/null || log "Warning: '$tool' not found; whitelist/ops or pack updates may fail."
done

exec bash ./launch.sh
'''

# --------------------------------------------------------------------------
# Installation script (runs once as root in ghcr.io/pelican-eggs/installers:debian)
# Placeholders: @@START@@ (pelican-start.sh) @@FULL@@
# --------------------------------------------------------------------------
INSTALL_SCRIPT = r'''#!/bin/bash
set -euo pipefail
export DEBIAN_FRONTEND=noninteractive
apt-get update -qq
apt-get install -y -qq curl ca-certificates busybox-static

mkdir -p /mnt/server/.bin /mnt/server/custom_mods /mnt/server/custom_config
cd /mnt/server

# jq: the Debian binary needs shared libraries the Java yolk may not have, so ship
# the official static build for this CPU architecture.
case "$(uname -m)" in
    x86_64) JQ_ARCH="amd64" ;;
    aarch64|arm64) JQ_ARCH="arm64" ;;
    *) echo "Unsupported CPU architecture: $(uname -m)"; exit 1 ;;
esac
echo "Installing static jq (${JQ_ARCH})..."
curl -fsSL --retry 3 "https://github.com/jqlang/jq/releases/download/jq-1.7.1/jq-linux-${JQ_ARCH}" -o .bin/jq
chmod +x .bin/jq
.bin/jq --version

# unzip: fallback for images without it (static busybox applet). pelican-start.sh
# puts .bin at the END of PATH, so a real unzip in the image is always preferred.
cp -f "$(command -v busybox)" .bin/busybox
ln -sf busybox .bin/unzip

cat << 'EOF' > pelican-start.sh
@@START@@EOF
sed -i 's/\r$//' pelican-start.sh
chmod +x pelican-start.sh

# Download pack.env + launch.sh (fails the install if GitHub can't be reached).
bash pelican-start.sh --fetch-only

echo "Installation complete! Start the server, accept the Minecraft EULA when prompted, and @@FULL@@ will download and launch."
'''


