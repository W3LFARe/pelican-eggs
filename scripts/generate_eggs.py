"""Generate the Pelican/Pterodactyl Egg JSON files from a single template.

    python3 scripts/generate_eggs.py          # (re)write both egg files
    python3 scripts/generate_eggs.py --check  # exit 1 if the files are out of date

The Eggs are ~95% identical, so everything lives here. Edit this file, run it,
commit the result. Never hand-edit the generated JSON (bash that has been
JSON-escaped is very easy to break).
"""
